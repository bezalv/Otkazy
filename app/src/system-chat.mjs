// Точный маркер Bitrix, а не любое упоминание пропущенного звонка клиентом.
// Вызвавшая сторона обязана предварительно проверить отсутствие вложений.
export function isMissedCallSystemMessage(value) {
  return /^\s*\[\s*СИСТЕМНОЕ\s+СООБЩЕНИЕ\s*\]\s*[-–—]\s*Пропущенный\s+звонок\s*$/iu.test(String(value || ''));
}
