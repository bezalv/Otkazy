var fs = require('fs');
var path = require('path');

var src = fs.readFileSync(path.join(__dirname, '..', '..', 'prototype', 'lib', 'no-conversation.js'), 'utf8');
var D = new Function(src + '\nreturn { detectNoConversation: detectNoConversation, NOTALK_MAX_SEC: NOTALK_MAX_SEC, NOTALK_MEANINGFUL_CHARS: NOTALK_MEANINGFUL_CHARS, NOTALK_MANAGER_REST_CHARS: NOTALK_MANAGER_REST_CHARS, NOTALK_ZERO_SEC_CHARS: NOTALK_ZERO_SEC_CHARS };')();

var pass = 0, fail = 0;
function check(name, client, manager, sec, expect, isMono) {
  var r = D.detectNoConversation(client, manager, sec, isMono);
  var got = r ? r.reason : 'нет';
  if (got === expect) { pass++; console.log('  ok   ' + name + ' → ' + got); }
  else {
    fail++;
    console.log('  FAIL ' + name + '\n       получил: ' + got + (r ? ' («' + (r.matched || '') + '», остаток «' + r.rest + '»)' : '') + '\n       ожидал:  ' + expect);
  }
}

