-- Изолированная синтетическая схема. Типы, NULL и значения по умолчанию получены
-- из information_schema существующих таблиц 05.11.2026. Клиентских данных нет.
CREATE ROLE anon;
CREATE ROLE authenticated;

CREATE TABLE public.lost_audio_wait (
  deal_id bigint NOT NULL,
  lose_date timestamp with time zone NOT NULL,
  state text NOT NULL,
  first_seen_at timestamp with time zone NOT NULL,
  deadline_at timestamp with time zone NOT NULL,
  next_check_at timestamp with time zone NOT NULL,
  pending_calls jsonb DEFAULT '[]'::jsonb NOT NULL,
  observations jsonb DEFAULT '{}'::jsonb NOT NULL,
  silent boolean DEFAULT false NOT NULL,
  screenshots boolean DEFAULT false NOT NULL,
  checks integer DEFAULT 0 NOT NULL,
  lease_until timestamp with time zone,
  updated_at timestamp with time zone DEFAULT now() NOT NULL,
  PRIMARY KEY (deal_id),
  CHECK (state IN ('waiting', 'done', 'expired', 'cancelled'))
);

CREATE TABLE public.lost_audio_wait_config (
  id boolean DEFAULT true NOT NULL,
  enabled_at timestamp with time zone DEFAULT now() NOT NULL,
  PRIMARY KEY (id),
  CHECK (id)
);

