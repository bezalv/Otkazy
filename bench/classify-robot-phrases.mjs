// Разбор стоп-листа системы обзвона (tasks/2026-09-30-robot-phrases.txt) на три группы.
// Брать список целиком нельзя: боты-«секретари» имитируют людей, и часть фраз — обычные
// слова клиента. Если метить по ним, потеряем живые отказы.
//
// A — однозначно машина: сообщения оператора, голосовая почта, самоназвание бота.
// B — шутки и отговорки ботов, которых живой клиент продавцу окон не скажет.
// C — может сказать живой клиент: как самостоятельный признак не используется.
//
// Запуск: node bench/classify-robot-phrases.mjs
import fs from 'node:fs';
import path from 'node:path';

const ROOT = path.resolve(import.meta.dirname, '..');

const norm = (s) => s.toLowerCase().replace(/ё/g, 'е')
  .replace(/[.,!?;:()"«»\-–—'"]/g, ' ').replace(/\s+/g, ' ').trim();

// ── группа A: однозначно машина ─────────────────────────────────────────────
const A_MARKERS = [
  // сообщения оператора связи
  'вне зоны', 'вызываемый', 'абонент', 'абоненту', 'отключен', 'не может ответить',
  'не берет трубку', 'не в сети', 'недоступен', 'не доступен', 'занята линия', 'линия занята',
  'аппарат', 'сеть перегружена', 'номер не существует', 'номер изменен',
  // голосовая почта
  'голосовая почта', 'почтовый ящик', 'после звукового сигнала', 'после сигнала',
  'оставьте сообщение', 'оставить сообщение', 'запишите сообщение', 'запись разговор',
  // англоязычные сообщения оператора
  'not available', 'please try again', 'the number', 'at the moment', 'try again later',
  'disconnect', 'is busy', 'out of', 'switched off',
  // самоназвание бота и антиспам-сервисы
  'автоответчик', 'виртуальн', 'ассистент', 'помощник', 'помошник', 'секретар',
  'защитник', 'умный бот', 'защита от спама', 'антиспам', 'робот отвечает', 'бот отвечает',
  'я не человек', 'я программа', 'я сервис',
  // передача сообщения
  'что передать', 'что нужно передать', 'передам', 'передать сообщение',
  'сообщение отправлено', 'сообщение готово', 'сообщение достигло', 'достигло',
  'я записал', 'я записала', 'зафиксировал', 'зафиксировала',
  // проверка звонящего ботом
  'знакомы с абонентом', 'личному или деловому', 'личный или деловой',
  // технические подсказки
  'тоновый', 'тональн', 'пин код', 'пин-код', 'нажмите', 'наберите добавочный', 'добавочный'
];

// ── группа B: бот-smalltalk ─────────────────────────────────────────────────
const B_MARKERS = [
  'единорог', 'в слова сыграем', 'в слова поиграем', 'чур первый', 'в бар', 'спамер',
  'руки крюки', 'рюки крюки', 'век бы с вами', 'живой человек или робот', 'робот или человек',
  'живой человек или автоответчик', 'вы робот', 'вы точно человек', 'человек или компьютер',
  'вы случайно не робот', 'вы живой', 'анекдот', 'шутк', 'загадк', 'стих', 'спою', 'песн',
  'скучно', 'поболтаем', 'о жизни', 'смысл жизни', 'как дела у вас там',
  'я подумаю над вашим предложением и передам'
];

// ── фон, который НЕ является машиной ────────────────────────────────────────
// Объявления метро и транспорта слышны у живого клиента.
const BACKGROUND = ['двери закрываются', 'уважаемые пассажиры', 'станция', 'осторожно двери',
  'следующая остановка', 'поезд следует'];

const raw = fs.readFileSync(path.join(ROOT, 'tasks', '2026-09-30-robot-phrases.txt'), 'utf8');
const phrases = raw.split(/\r?\n/).map(s => s.trim()).filter(Boolean);

const A = [], B = [], C = [], BG = [];
for (const p of phrases) {
  const n = norm(p);
  if (BACKGROUND.some(m => n.includes(m))) { BG.push(p); continue; }
  if (B_MARKERS.some(m => n.includes(m))) { B.push(p); continue; }
  if (A_MARKERS.some(m => n.includes(m))) { A.push(p); continue; }
  C.push(p);
}

console.log(`Всего фраз в списке: ${phrases.length}`);
console.log(`  A (однозначно машина): ${A.length}`);
console.log(`  B (бот-smalltalk):     ${B.length}`);
console.log(`  C (может сказать живой клиент — как признак НЕ используем): ${C.length}`);
console.log(`  фон транспорта (не машина): ${BG.length}`);

fs.writeFileSync(path.join(ROOT, 'bench', 'data', 'robot-phrases-groups.json'),
  JSON.stringify({ A, B, C, BACKGROUND: BG }, null, 2), 'utf8');

const show = (title, arr) => {
  console.log('\n' + '='.repeat(78));
  console.log(`${title} — ${arr.length}`);
  console.log('='.repeat(78));
  for (const p of arr) console.log('  ' + p);
};

show('ГРУППА B: бот-smalltalk (метим по одной фразе)', B);
show('ФОН ТРАНСПОРТА: не метим', BG);

// Спорные в A: короткие фразы и те, что теоретически может сказать человек.
const A_SUSPECT = A.filter(p => {
  const n = norm(p);
  if (n.split(' ').length <= 2) return true;                      // слишком короткие
  if (/(дорого|подума|не надо|не нужн|перезвон|спасибо|не актуальн|занят)/.test(n)) return true;
  return false;
});
show('СПОРНЫЕ В A: короткие или похожие на живую речь — проверить глазами', A_SUSPECT);

// Спорные в C: те, что похожи на машину, но попали в C.
const C_SUSPECT = C.filter(p => {
  const n = norm(p);
  return /(сообщени|звонок|номер|связ|трубк|линия|оператор|соединени|вызов|жду подробност|расскажите вкратце|откуда вы звоните)/.test(n);
});
show('СПОРНЫЕ В C: похожи на машину, но оставлены как живые — проверить глазами', C_SUSPECT);

console.log(`\nГруппы сохранены: bench/data/robot-phrases-groups.json`);
